// Generates lib/booking/alarmSound.ts's ALARM_SOUND_DATA_URI: a longer,
// pleasant reminder chime — a soft major-triad arpeggio (C5-E5-G5-C6) played
// twice, with a fast-attack/slow-decay bell-like envelope, ~3.75s total.
//
//   node scripts/generate-alarm-sound.mjs
import { writeFileSync } from 'node:fs'

const SAMPLE_RATE = 22050

function noteSamples(freq, durationSec, gain = 0.5) {
  const n = Math.floor(SAMPLE_RATE * durationSec)
  const out = new Float32Array(n)
  for (let i = 0; i < n; i++) {
    const t = i / SAMPLE_RATE
    // Fast attack (~8ms), exponential decay across the note's tail — a soft
    // bell/xylophone envelope rather than a harsh beep.
    const attack = Math.min(1, t / 0.008)
    const decay = Math.exp(-t * 3.2)
    const envelope = attack * decay
    // A touch of the octave harmonic keeps it from sounding like a flat sine buzzer.
    const sample = Math.sin(2 * Math.PI * freq * t) * 0.85 + Math.sin(2 * Math.PI * freq * 2 * t) * 0.15
    out[i] = sample * envelope * gain
  }
  return out
}

function silence(durationSec) {
  return new Float32Array(Math.floor(SAMPLE_RATE * durationSec))
}

function concat(arrays) {
  const total = arrays.reduce((sum, a) => sum + a.length, 0)
  const out = new Float32Array(total)
  let offset = 0
  for (const a of arrays) {
    out.set(a, offset)
    offset += a.length
  }
  return out
}

const C5 = 523.25
const E5 = 659.25
const G5 = 783.99
const C6 = 1046.5

const NOTE_DUR = 0.34
const GAP = 0.045

function phrase() {
  return concat([
    noteSamples(C5, NOTE_DUR, 0.5),
    silence(GAP),
    noteSamples(E5, NOTE_DUR, 0.5),
    silence(GAP),
    noteSamples(G5, NOTE_DUR, 0.5),
    silence(GAP),
    noteSamples(C6, NOTE_DUR * 1.6, 0.55),
  ])
}

const full = concat([phrase(), silence(0.35), phrase()])

// Encode as 16-bit PCM mono WAV.
const numSamples = full.length
const dataSize = numSamples * 2
const buffer = Buffer.alloc(44 + dataSize)

buffer.write('RIFF', 0)
buffer.writeUInt32LE(36 + dataSize, 4)
buffer.write('WAVE', 8)
buffer.write('fmt ', 12)
buffer.writeUInt32LE(16, 16)
buffer.writeUInt16LE(1, 20) // PCM
buffer.writeUInt16LE(1, 22) // mono
buffer.writeUInt32LE(SAMPLE_RATE, 24)
buffer.writeUInt32LE(SAMPLE_RATE * 2, 28)
buffer.writeUInt16LE(2, 32)
buffer.writeUInt16LE(16, 34)
buffer.write('data', 36)
buffer.writeUInt32LE(dataSize, 40)

for (let i = 0; i < numSamples; i++) {
  const clamped = Math.max(-1, Math.min(1, full[i]))
  buffer.writeInt16LE(Math.round(clamped * 32767), 44 + i * 2)
}

const dataUri = `data:audio/wav;base64,${buffer.toString('base64')}`

writeFileSync(
  new URL('../lib/booking/alarmSound.ts', import.meta.url),
  `/**
 * A gentle reminder chime (~3.75s) for the session heads-up alarm (M21 #6
 * follow-up) — a soft major-triad arpeggio (C5-E5-G5-C6) played twice, with
 * a fast-attack/slow-decay bell-like envelope so it reads as a pleasant
 * "time to check on this" cue rather than a harsh alert beep. Embedded as a
 * data URI so the alarm has no external asset dependency. Generated by
 * scripts/generate-alarm-sound.mjs — run that again if it needs to change.
 */
export const ALARM_SOUND_DATA_URI = '${dataUri}'
`,
)

console.log('wrote lib/booking/alarmSound.ts —', (numSamples / SAMPLE_RATE).toFixed(2) + 's', `(${dataUri.length} chars)`)
